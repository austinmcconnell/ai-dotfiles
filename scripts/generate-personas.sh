#!/bin/bash
set -euo pipefail

# ---------------------------------------------------------------
# generate-personas.sh
#
# Builds the Claude Code persona files with their steering inlined.
#
# Claude Code uses a persona's markdown body verbatim as its system prompt and
# does not expand `@path` imports there (they work only in CLAUDE.md, AGENTS.md
# and rules files), so the steering has to be part of the installed file itself.
# Each output file is the hand-authored persona body from
# etc/claude-code/agents/<name>.md followed by every steering doc in the
# persona's domain (see install/persona-domains.sh) plus
# security/env-file-protection.md, with YAML frontmatter stripped.
#
# After writing, each output is checked to contain every inlined doc. Any
# failure prints to stderr and exits 1; nothing is skipped silently.
#
# Usage: generate-personas.sh [OUT_DIR]   (default: $HOME/.claude/agents)
# ---------------------------------------------------------------

AI_DOTFILES_DIR="${AI_DOTFILES_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

if [[ ! -f "$AI_DOTFILES_DIR/install/persona-domains.sh" || ! -d "$AI_DOTFILES_DIR/etc/ai/steering" ]]; then
    echo "✗ AI_DOTFILES_DIR=$AI_DOTFILES_DIR does not look like the ai-dotfiles repo" >&2
    exit 1
fi

source "$AI_DOTFILES_DIR/install/persona-domains.sh"

SOURCE_DIR="$AI_DOTFILES_DIR/etc/claude-code/agents"
STEERING_DIR="$AI_DOTFILES_DIR/etc/ai/steering"
OUT_DIR="${1:-$HOME/.claude/agents}"
GENERATED_MARKER="GENERATED by scripts/generate-personas.sh"

fail() {
    echo "✗ $*" >&2
    exit 1
}

# Print a steering doc without its YAML frontmatter (path-scoping metadata that
# means nothing inside a system prompt).
strip_frontmatter() {
    if head -1 "$1" | grep -q '^---$'; then
        sed '1,/^---$/d' "$1"
    else
        cat "$1"
    fi
}

# Collect host-local steering source `domain=path` pairs, mirroring the
# skill-sources seam in install/ai-tools.sh. Company-specific steering lives
# outside this (soon public) repo under ~/.extra, so it is never published yet
# still loads for the author. Pairs come from two optional sources:
#   - $EXTRA_STEERING_SOURCES env var — colon-separated domain=path pairs
#   - ~/.extra/steering-sources file  — one domain=path pair per line (# ok)
# Both absent (the public-cloner case) is normal: the array stays empty and the
# generator inlines only in-repo steering. An entry with no `=` is skipped.
extra_steering_pairs() {
    local line
    if [[ -n "${EXTRA_STEERING_SOURCES:-}" ]]; then
        local env_pairs
        IFS=':' read -r -a env_pairs <<<"$EXTRA_STEERING_SOURCES"
        for line in "${env_pairs[@]}"; do
            [[ "$line" == *=* ]] && printf '%s\n' "$line"
        done
    fi
    if [[ -f "$HOME/.extra/steering-sources" ]]; then
        while IFS= read -r line; do
            line="${line%%#*}"
            line="${line#"${line%%[![:space:]]*}"}"
            line="${line%"${line##*[![:space:]]}"}"
            [[ "$line" == *=* ]] && printf '%s\n' "$line"
        done <"$HOME/.extra/steering-sources"
    fi
}

# Print the host-local directory for each pair whose domain matches $1. Expands a
# leading ~/ to $HOME (literal prefix check — tilde expansion does not fire inside
# a variable). Does not test existence; the caller decides how to treat a missing
# path (A1 skips it silently; A2 adds the resolve-or-skip assertion).
extra_steering_dirs_for_domain() {
    local want="$1" pair pair_domain pair_path
    while IFS= read -r pair; do
        [[ -n "$pair" ]] || continue
        pair_domain="${pair%%=*}"
        [[ "$pair_domain" == "$want" ]] || continue
        pair_path="${pair#*=}"
        if [[ "${pair_path#\~/}" != "$pair_path" ]]; then
            pair_path="$HOME/${pair_path#\~/}"
        fi
        printf '%s\n' "$pair_path"
    done < <(extra_steering_pairs)
}

# Print a listed domain's host-local *.md paths to stdout (one per line). Every
# path reaching here was explicitly listed in a steering-source, so a missing
# path or an empty dir is a stale/typo'd entry, not the public-cloner case —
# warn loudly to stderr and skip (non-fatal: the overlay is optional, and the
# in-repo docs already satisfy the generator's non-empty guard). This is the
# shell-conventions "never silently pass a dangling path" rule for this seam;
# it deliberately diverges from the skill-sources seam's silent skip. Printing
# rather than a nameref keeps this bash 3.2-compatible (macOS system bash).
extra_steering_docs() {
    local domain="$1" dir doc found
    while IFS= read -r dir; do
        [[ -n "$dir" ]] || continue
        if [[ ! -d "$dir" ]]; then
            echo "⚠ SKIPPED host-local steering for '$domain': $dir does not exist" >&2
            continue
        fi
        found=0
        for doc in "$dir"/*.md; do
            [[ -f "$doc" ]] || continue
            printf '%s\n' "$doc"
            found=1
        done
        ((found)) ||
            echo "⚠ SKIPPED host-local steering for '$domain': no *.md in $dir" >&2
    done < <(extra_steering_dirs_for_domain "$domain")
}

# Make OUT_DIR a real directory. A symlink there (the previous install linked the
# whole repo directory) is removed without touching its target.
prepare_out_dir() {
    if [[ -L "$OUT_DIR" ]]; then
        rm -f "$OUT_DIR"
    elif [[ -e "$OUT_DIR" && ! -d "$OUT_DIR" ]]; then
        fail "$OUT_DIR exists and is not a directory"
    fi
    mkdir -p "$OUT_DIR"
}

# Refuse to overwrite a hand-written file; replace symlinks and earlier output.
check_target() {
    local target="$1"
    if [[ -L "$target" ]]; then
        rm -f "$target"
    elif [[ -e "$target" ]] && ! grep -qF "$GENERATED_MARKER" "$target"; then
        fail "$target exists and was not generated by this script; refusing to overwrite it"
    fi
}

# Write the persona body followed by each steering doc. Args: persona, doc paths.
build_persona() {
    local persona="$1" doc
    shift
    cat "$SOURCE_DIR/$persona.md"
    printf '\n<!-- %s from etc/claude-code/agents/%s.md; do not edit. -->\n' \
        "$GENERATED_MARKER" "$persona"
    for doc in "$@"; do
        printf '\n<!-- steering: %s -->\n\n' "${doc#"$STEERING_DIR"/}"
        strip_frontmatter "$doc"
    done
}

# Assert the output holds the first line of every inlined doc. Args: output, doc paths.
verify_persona() {
    local output="$1" doc first
    shift
    for doc in "$@"; do
        first="$(strip_frontmatter "$doc" | grep -m1 -v '^[[:space:]]*$' || true)"
        [[ -n "$first" ]] || fail "${doc#"$STEERING_DIR"/} has no content to inline"
        grep -qxF -- "$first" "$output" ||
            fail "$output is missing ${doc#"$STEERING_DIR"/}"
    done
}

prepare_out_dir

# Check every target first so a refusal leaves the directory untouched, not half-updated.
for persona in "${PERSONAS[@]}"; do
    check_target "$OUT_DIR/$persona.md"
done

for persona in "${PERSONAS[@]}"; do
    domain="$(persona_domain "$persona")" || fail "no steering domain mapped for $persona"
    [[ -f "$SOURCE_DIR/$persona.md" ]] || fail "persona source not found: $SOURCE_DIR/$persona.md"

    docs=()
    for doc in "$STEERING_DIR/$domain"/*.md; do
        [[ -f "$doc" ]] && docs+=("$doc")
    done

    # Append host-local steering for this domain (see extra_steering_pairs).
    # Absent sources add nothing; a listed-but-missing path warns (see helper).
    while IFS= read -r extra_doc; do
        [[ -n "$extra_doc" ]] && docs+=("$extra_doc")
    done < <(extra_steering_docs "$domain")

    ((${#docs[@]} > 0)) || fail "no steering docs found in $STEERING_DIR/$domain"

    # Every persona also gets the shared domain, the same one every kiro agent
    # globs (file://~/.kiro/steering/shared/**/*.md).
    shared_docs=()
    for doc in "$STEERING_DIR/shared"/*.md; do
        [[ -f "$doc" ]] && shared_docs+=("$doc")
    done
    ((${#shared_docs[@]} > 0)) || fail "no steering docs found in $STEERING_DIR/shared"
    docs+=("${shared_docs[@]}")

    security_doc="$STEERING_DIR/security/env-file-protection.md"
    [[ -f "$security_doc" ]] || fail "steering doc not found: $security_doc"
    docs+=("$security_doc")

    target="$OUT_DIR/$persona.md"
    build_persona "$persona" "${docs[@]}" >"$target.tmp"
    mv -f "$target.tmp" "$target"
    verify_persona "$target" "${docs[@]}"
    echo "✓ Generated $target (${#docs[@]} steering docs)"
done
