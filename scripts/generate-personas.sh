#!/bin/bash
set -euo pipefail

# ---------------------------------------------------------------
# generate-personas.sh
#
# Builds the Claude Code persona files with their steering inlined.
#
# Claude Code uses a persona's markdown body verbatim as its system prompt and
# does not expand `@path` imports there (they work only in CLAUDE.md, AGENTS.md
# and rules files), so the steering has to be part of the installed file itself.
# Each output file is the hand-authored persona body from
# etc/claude-code/agents/<name>.md followed by every steering doc in the
# persona's domain (see install/persona-domains.sh) plus
# security/env-file-protection.md, with YAML frontmatter stripped.
#
# After writing, each output is checked to contain every inlined doc. Any
# failure prints to stderr and exits 1; nothing is skipped silently.
#
# Usage: generate-personas.sh [OUT_DIR]   (default: $HOME/.claude/agents)
# ---------------------------------------------------------------

AI_DOTFILES_DIR="${AI_DOTFILES_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

source "$AI_DOTFILES_DIR/install/persona-domains.sh"

SOURCE_DIR="$AI_DOTFILES_DIR/etc/claude-code/agents"
STEERING_DIR="$AI_DOTFILES_DIR/etc/ai/steering"
OUT_DIR="${1:-$HOME/.claude/agents}"
GENERATED_MARKER="GENERATED by scripts/generate-personas.sh"

fail() {
    echo "✗ $*" >&2
    exit 1
}

# Print a steering doc without its YAML frontmatter (path-scoping metadata that
# means nothing inside a system prompt).
strip_frontmatter() {
    if head -1 "$1" | grep -q '^---$'; then
        sed '1{/^---$/!q}; 1,/^---$/d' "$1"
    else
        cat "$1"
    fi
}

# Make OUT_DIR a real directory. A symlink there (the previous install linked the
# whole repo directory) is removed without touching its target.
prepare_out_dir() {
    if [[ -L "$OUT_DIR" ]]; then
        rm -f "$OUT_DIR"
    elif [[ -e "$OUT_DIR" && ! -d "$OUT_DIR" ]]; then
        fail "$OUT_DIR exists and is not a directory"
    fi
    mkdir -p "$OUT_DIR"
}

# Refuse to overwrite a hand-written file; replace symlinks and earlier output.
check_target() {
    local target="$1"
    if [[ -L "$target" ]]; then
        rm -f "$target"
    elif [[ -e "$target" ]] && ! grep -qF "$GENERATED_MARKER" "$target"; then
        fail "$target exists and was not generated by this script; refusing to overwrite it"
    fi
}

# Write the persona body followed by each steering doc. Args: persona, doc paths.
build_persona() {
    local persona="$1" doc
    shift
    cat "$SOURCE_DIR/$persona.md"
    printf '\n<!-- %s from etc/claude-code/agents/%s.md; do not edit. -->\n' \
        "$GENERATED_MARKER" "$persona"
    for doc in "$@"; do
        printf '\n<!-- steering: %s -->\n\n' "${doc#"$STEERING_DIR"/}"
        strip_frontmatter "$doc"
    done
}

# Assert the output holds the first line of every inlined doc. Args: output, doc paths.
verify_persona() {
    local output="$1" doc first
    shift
    for doc in "$@"; do
        first="$(strip_frontmatter "$doc" | grep -m1 -v '^[[:space:]]*$' || true)"
        [[ -n "$first" ]] || fail "${doc#"$STEERING_DIR"/} has no content to inline"
        grep -qxF -- "$first" "$output" ||
            fail "$output is missing ${doc#"$STEERING_DIR"/}"
    done
}

prepare_out_dir

# Check every target first so a refusal leaves the directory untouched, not half-updated.
for persona in "${PERSONAS[@]}"; do
    check_target "$OUT_DIR/$persona.md"
done

for persona in "${PERSONAS[@]}"; do
    domain="$(persona_domain "$persona")" || fail "no steering domain mapped for $persona"
    [[ -f "$SOURCE_DIR/$persona.md" ]] || fail "persona source not found: $SOURCE_DIR/$persona.md"

    docs=()
    for doc in "$STEERING_DIR/$domain"/*.md; do
        [[ -f "$doc" ]] && docs+=("$doc")
    done
    ((${#docs[@]} > 0)) || fail "no steering docs found in $STEERING_DIR/$domain"

    security_doc="$STEERING_DIR/security/env-file-protection.md"
    [[ -f "$security_doc" ]] || fail "steering doc not found: $security_doc"
    docs+=("$security_doc")

    target="$OUT_DIR/$persona.md"
    build_persona "$persona" "${docs[@]}" >"$target.tmp"
    mv -f "$target.tmp" "$target"
    verify_persona "$target" "${docs[@]}"
    echo "✓ Generated $target (${#docs[@]} steering docs)"
done
